package a26_0812.travel;

public class Travel1 {
    private String city;
    private int days;
    private int cost;

    public Travel1(String city, int days, int cost) {
        this.city = city;
        this.days = days;
        this.cost = cost;
    }

    public String getCity() {
        return city;
    }

    public int getDays() {
        return days;
    }

    public int getCost() {
        return cost;
    }

}
